import { formatDateTime } from "@/lib/time";
import { formatTokenNo } from "@/lib/tokens";
import DataTable, { type Column } from "@/components/data-table/DataTable";
import Badge from "@/components/ui/Badge";
import type { Token } from "@/types";
import TokenProgressBadge from "./TokenProgressBadge";
import Button from "@/components/ui/Button";

interface TokenTableProps {
  tokens: Token[];
  showCreator: boolean;
  loading?: boolean;
  showDiscard?: boolean;
  onDiscard?: (token: Token) => void;
}

const ORDER: Record<string, number> = {
  pending: 0,
  ongoing: 1,
  completed: 2,
};

const getTokenSeq = (t: Token): number => {
  const n = Number(
    (t as any).tokenNumber ?? (t as any).token_number ?? 0
  );
  return Number.isFinite(n) && n > 0 ? n : 0;
};

const getLinkedLabel = (t: Token): string | null => {
  const linked = t.linkedRecord as any;
  if (!linked) return null;

  // Object shape: { kind, id }
  if (typeof linked === "object") {
    const kind =
      linked.kind === "caller" || linked.kind === "Caller"
        ? "Caller"
        : "Support";
    const id = linked.id != null ? String(linked.id) : "";
    const short =
      id.length > 8 ? `${id.slice(0, 8)}…` : id || "—";
    return `${kind} #${short}`;
  }

  // Plain id string/number from API
  const id = String(linked);
  const short = id.length > 8 ? `${id.slice(0, 8)}…` : id;
  return `Record #${short}`;
};

const TokenTable = ({
  tokens,
  showCreator,
  loading,
  showDiscard = false,
  onDiscard,
}: TokenTableProps) => {
  const columns: Column<Token>[] = [
    {
      key: "token",
      header: "Token",
      sortValue: (t) => getTokenSeq(t) || String(t.id),
      render: (t) => (
        <span className="whitespace-nowrap font-semibold text-brand">
          {formatTokenNo(t)}
        </span>
      ),
    },
    {
      key: "name",
      header: "Customer",
      sortValue: (t) => t.customerName || "",
      render: (t) => (
        <span className="font-medium">{t.customerName || "—"}</span>
      ),
    },
    {
      key: "kind",
      header: "Type",
      sortValue: (t) => t.kind,
      render: (t) => <span className="capitalize">{t.kind}</span>,
    },
    {
      key: "mobile",
      header: "Phone No.",
      sortValue: (t) => t.mobileNo || "",
      render: (t) => t.mobileNo || "—",
    },
    {
      key: "software",
      header: "Software",
      sortValue: (t) => t.software || "",
      render: (t) => t.software || "—",
    },
    {
      key: "progress",
      header: "Work Progress",
      sortValue: (t) => ORDER[String(t.progress)] ?? 99,
      render: (t) => <TokenProgressBadge progress={t.progress} />,
    },
    {
      key: "created",
      header: "Generated",
      sortValue: (t) => t.createdAt || "",
      render: (t) => (
        <span className="whitespace-nowrap">
          {t.createdAt ? formatDateTime(t.createdAt) : "—"}
        </span>
      ),
    },
    {
      key: "by",
      header: "Generated By",
      hidden: !showCreator,
      sortValue: (t) =>
        (t.createdBy as any)?.name ||
        String((t.createdBy as any)?.id || ""),
      render: (t) =>
        (t.createdBy as any)?.name ||
        String((t.createdBy as any)?.id || "—"),
    },
    {
      key: "linked",
      header: "Linked Record",
      render: (t) => {
        const label = getLinkedLabel(t);
        return label ? (
          <Badge tone="success">{label}</Badge>
        ) : (
          <span className="text-fg-subtle">—</span>
        );
      },
    },
    ...(showDiscard ? [{
      key: "actions",
      header: "Actions",
      align: "center" as const,
      render: (token: Token) => <Button variant="dangerOutline" size="sm" icon="trash" onClick={() => onDiscard?.(token)} aria-label={`Discard token ${formatTokenNo(token)}`}>Discard</Button>,
    } satisfies Column<Token>] : []),
  ];

  return (
    <DataTable
      caption="Tokens"
      columns={columns}
      rows={tokens}
      rowKey={(t) => String(t.id)}
      loading={loading}
      minWidth="900px"
      emptyTitle="No tokens yet."
      emptyMessage="Use Generate Token when a customer is waiting."
    />
  );
};

export default TokenTable;
