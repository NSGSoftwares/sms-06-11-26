import { useMemo, useState } from "react";
import { TOKEN_PROGRESS } from "@/config";
import { useAuth } from "@/hooks/useAuth";
import { useTokens } from "@/hooks/useTokens";
import {
  canUseTokens,
  isAdmin,
  visibleTokensTo,
} from "@/lib/permissions";
import { formatTokenNo } from "@/lib/tokens";
import { FilterBar, FilterField } from "@/components/records/FilterBar";
import Notice from "@/components/ui/Notice";
import ConfirmDialog from "@/components/ui/ConfirmDialog";
import { deleteToken } from "@/services/tokenService";
import { useToast } from "@/components/ui/ToastProvider";
import type { Token } from "@/types";
import TokenTable from "./TokenTable";

const TokensPage = () => {
  const { user } = useAuth();
  const { tokens, loading, loadError, reload } = useTokens();
  const toast = useToast();

  const [filter, setFilter] = useState("All");
  const [kindFilter, setKindFilter] = useState<"All" | "support" | "lead">("All");
  const [search, setSearch] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [discardTarget, setDiscardTarget] = useState<Token | null>(null);
  const [discarding, setDiscarding] = useState(false);

  if (!canUseTokens(user)) {
    return null;
  }

  // Shared queue: all tokens for admin + support
  const mine = useMemo(
    () => visibleTokensTo(user, tokens),
    [user, tokens]
  );

  const shown = useMemo(() => {
    const q = search.trim().toLowerCase();
    return mine.filter((token) => {
      const progressOk =
        filter === "All" || String(token.progress) === filter;
      if (!progressOk) return false;
      if (isAdmin(user) && kindFilter !== "All" && token.kind !== kindFilter) return false;
      if (!q) return true;
      const label = formatTokenNo(token).toLowerCase();
      return (
        token.customerName.toLowerCase().includes(q) ||
        String(token.mobileNo).includes(q) ||
        label.includes(q)
      );
    });
  }, [mine, filter, kindFilter, search, user]);

  const handleDiscard = async () => {
    if (!discardTarget || !isAdmin(user)) return;
    setDiscarding(true);
    try {
      await deleteToken(discardTarget.id);
      await reload();
      toast.success(`${formatTokenNo(discardTarget)} was discarded successfully.`, {
        title: "Token Discarded",
      });
      setDiscardTarget(null);
    } catch (e) {
      const message = e instanceof Error ? e.message : "Could not discard this token.";
      setError(message);
      toast.error(message, { title: "Discard Failed" });
    } finally {
      setDiscarding(false);
    }
  };

  return (
    <div className="w-full">
      <div className="mb-6">
        <h2 className="text-xl font-semibold text-fg">Tokens</h2>
        <p className="mt-1 text-sm text-fg-subtle">
          {isAdmin(user)
            ? "Every token generated by staff"
            : user?.role === "caller"
              ? "Lead tokens for caller follow-up. Set On Going when you begin; saving the lead form completes the token."
              : "Support tokens for customer assistance. Set On Going when you begin; saving the support form completes the token."}
        </p>
      </div>

      {error && (
        <Notice type="error" message={error} onClose={() => setError(null)} />
      )}
      {loadError && (
        <Notice type="error" message={loadError} onClose={() => void reload()} />
      )}

      <FilterBar
        shown={shown.length}
        total={mine.length}
        noun="tokens"
        active={filter !== "All" || (isAdmin(user) && kindFilter !== "All") || search !== ""}
        onClear={() => {
          setFilter("All");
          setKindFilter("All");
          setSearch("");
        }}
      >
        {isAdmin(user) && <FilterField label="Token Type">
          {(p) => <select {...p} value={kindFilter} onChange={(e) => setKindFilter(e.target.value as typeof kindFilter)}>
            <option value="All">All token types</option>
            <option value="support">Support tokens</option>
            <option value="lead">Lead tokens</option>
          </select>}
        </FilterField>}
        <FilterField label="Progress">
          {(p) => (
            <select
              {...p}
              value={filter}
              onChange={(e) => setFilter(e.target.value)}
            >
              <option value="All">All</option>
              {TOKEN_PROGRESS.map((item) => (
                <option key={item.value} value={item.value}>
                  {item.label}
                </option>
              ))}
            </select>
          )}
        </FilterField>

        <FilterField label="Search">
          {(p) => (
            <input
              {...p}
              type="search"
              value={search}
              onChange={(e) => setSearch(e.target.value)}
              placeholder="Name / phone / token..."
            />
          )}
        </FilterField>
      </FilterBar>

      <TokenTable
        tokens={shown}
        showCreator={isAdmin(user) || user?.role === "support"}
        loading={loading}
        showDiscard={isAdmin(user)}
        onDiscard={setDiscardTarget}
      />
      {discardTarget && <ConfirmDialog
        title="Discard this token?"
        message={<span>Token <strong>{formatTokenNo(discardTarget)}</strong> for {discardTarget.customerName} will be permanently removed from the queue.</span>}
        confirmLabel="Discard token"
        cancelLabel="Keep token"
        danger
        busy={discarding}
        onConfirm={() => void handleDiscard()}
        onCancel={() => !discarding && setDiscardTarget(null)}
      />}
    </div>
  );
};

export default TokensPage;
